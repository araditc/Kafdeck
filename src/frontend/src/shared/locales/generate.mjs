import fs from 'node:fs';
const directory = new URL('./', import.meta.url);
const en = JSON.parse(fs.readFileSync(new URL('en.json', directory), 'utf8'));
const fa = JSON.parse(fs.readFileSync(new URL('fa.json', directory), 'utf8'));
if (JSON.stringify(Object.keys(en).sort()) !== JSON.stringify(Object.keys(fa).sort())) throw Error('English/Persian keys differ.');
for (const [key, text] of Object.entries(en)) {
  if (text !== key || typeof fa[key] !== 'string' || !fa[key].trim()) throw Error('Invalid message: ' + key);
  const placeholders = value => (value.match(/\{\d+\}/g) ?? []).sort().join(',');
  if (placeholders(key) !== placeholders(fa[key])) throw Error('Interpolation mismatch: ' + key);
  if (/[\u202a-\u202e\u2066-\u2069]/.test(fa[key])) throw Error('Use markup for bidi isolation: ' + key);
}
fs.writeFileSync(new URL('messages.ts', directory), '/** Generated by generate.mjs from en.json/fa.json. English is authoritative; plain text only. */\nexport const messages: Readonly<Record<string, string>> = ' + JSON.stringify(fa, null, 2) + ';\n');
